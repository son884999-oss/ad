export function uiText(text: string, easyMode: boolean) {
  if (!easyMode) return text
  const whole = easyUiDictionary[text]
  if (whole !== undefined) return whole
  const sentences = text.trim().split(/(?<=[.!?])\s+/)
  if (sentences.length < 2) return text
  let changed = false
  const easy = sentences.map((sentence) => {
    const value = easyUiDictionary[sentence]
    if (value === undefined) return sentence
    changed = true
    return value
  })
  return changed ? easy.filter(Boolean).join(" ") : text
}
